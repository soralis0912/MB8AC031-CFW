#!/usr/bin/env python3
"""config/drivers.json + config/devices/*.json -> one device's row, as C

What differs between devices is how I2C is reached, the demodulator, the
tuner and the card interface.  All of that lives outside the chip or on
another path, so it is not hard-coded in C: config/ holds it as tables and
this script turns one row into C.  Adding a device means adding one JSON
file.

Every image is built for exactly one device -- one FRC1 container per
product.  So the row is fixed when the image is
linked: build.py writes build/board_<id>.c, which defines `fw_board`, and
links it into that device's image.  Nothing at run time works out which
device it is on.

The tables come in two parts:

    config/drivers.json     the driver table and the evidence levels, shared
                            across devices
    config/devices/<id>.json
                            one file per device whose image has run on real
                            hardware: which drivers it combines, its I2C
                            addresses and evidence levels
    config/untested/<id>.json
                            the same shape, for rows whose image has never
                            run on real hardware.  Once one runs, move it to
                            devices/.  The directory is the only record of
                            that

Exactly one row has `usb` null (`unknown`).  It names no product: it is the
row for an image that is not built for a device -- the image most tests
run.  Every part of it is unknown, so the
dispatchers answer FW_ENOTIMPL.

build.py uses:

    load(root)                  the tables, checked
    write_row(root, d, bid)     writes build/board_<bid>.c -> its path
    driver_sources(d)           every driver source and what it requires.
                                All are compiled into every image, so a
                                driver no device selects cannot rot silently

It also runs on its own:

    python3 genboards.py            # check the tables and print them
    python3 genboards.py --c dt295  # print the C for one device
"""
import json
import os
import sys

# This script lives in host/ and reads config/, so the default root is one up
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = {"t": "FW_SRC_T", "t2": "FW_SRC_T2", "s": "FW_SRC_S", "s2": "FW_SRC_S2"}
BAND_MAX = 2   # FW_BANDS in src/main/drivers.h
EV = {"unknown": "EV_UNKNOWN", "inferred": "EV_INFERRED", "measured": "EV_MEASURED"}
# Do not write config/devices/*.json in the output: "/*" inside a C comment
# trips -Wcomment
BANNER = "/* GENERATED by host/genboards.py from config/ -- do not edit. */"

DRIVERS = os.path.join("config", "drivers.json")
DEVICES = os.path.join("config", "devices")
UNTESTED = os.path.join("config", "untested")
# More device directories, each read like config/untested/.  Empty for a
# build; a test appends its own fixture rows here (tests/boards/) before it
# loads the tables, so it can link an image for a board shape that no real
# device in config/ has
EXTRA_DIRS = []
BUILD = "build"

CARD_UNKNOWN = 0xFF


def _read(path, where):
    if not os.path.exists(path):
        raise SystemExit(f"{where} is missing")
    with open(path, encoding="utf-8") as f:
        try:
            return json.load(f)
        except ValueError as e:
            raise SystemExit(f"{where}: cannot parse JSON: {e}")


def _files(root):
    """-> [(id, path to read, path to show, untested?), ...] by file name.

    Collects both config/devices/ and config/untested/; the only difference
    is whether an image built from the row has run on real hardware.
    """
    out, seen = [], {}
    for rel, is_un in ([(DEVICES, False), (UNTESTED, True)] +
                       [(x, True) for x in EXTRA_DIRS]):
        d = os.path.join(root, rel)
        if not os.path.isdir(d):
            continue
        for name in sorted(n for n in os.listdir(d) if n.endswith(".json")):
            bid = name[:-5]
            where = f"{rel}/{name}"
            if bid in seen:
                raise SystemExit(f"{where}: the same device is also in "
                                 f"{seen[bid]}; keep only one")
            seen[bid] = where
            out.append((bid, os.path.join(d, name), where, is_un))
    if not out:
        raise SystemExit(f"no device files in {DEVICES}/ or {UNTESTED}/")
    out.sort(key=lambda t: t[0])
    return out


def load(root=HERE):
    """The shared table plus every device file, checked, as one dict.

    d["boards"] is in file-name order; d["none"] is the id of the row that
    names no product.
    """
    d = _read(os.path.join(root, DRIVERS), DRIVERS)
    for key in ("drivers", "evidence_levels"):
        if key not in d:
            raise SystemExit(f"{DRIVERS}: '{key}' is missing")
    rows = []
    for bid, path, where, is_un in _files(root):
        b = _read(path, where)
        if b.get("id") != bid:
            raise SystemExit(f"{where}: id is '{b.get('id')}', which does not "
                             "match the file name (one file per device)")
        b["_file"] = where
        b["_untested"] = is_un
        rows.append(b)
    d["boards"] = rows
    d["_root"] = root
    _check(d)
    d["none"] = next(b["id"] for b in rows if not b.get("usb"))
    return d


def board(d, bid):
    for b in d["boards"]:
        if b["id"] == bid:
            return b
    raise SystemExit(f"no such device: {bid}\n  {DEVICES}/ and {UNTESTED}/"
                     " have: " + ", ".join(b["id"] for b in d["boards"]))


def untested(d):
    """Device ids in config/untested/ (never run on real hardware)."""
    return [b["id"] for b in d["boards"] if b["_untested"]]


def _usb(s):
    if not s:
        return 0
    vid, pid = s.split(":")
    return (int(vid, 16) << 16) | int(pid, 16)


def _num(v):
    if v is None:
        return 0
    return int(v, 16) if isinstance(v, str) else int(v)


def _driver(d, kind, name, where):
    if name is None:
        return None
    try:
        return d["drivers"][kind][name]
    except KeyError:
        raise SystemExit(f"{where}: '{name}' is not in drivers.{kind} of {DRIVERS}")


def _card(b):
    """The row's card entry, or "unknown" when there is none (docs/card.md)."""
    return b.get("card") or {"slot": None, "polarity": None,
                             "evidence": "unknown"}


def _ts(b):
    """The row's TS-input entry, or "unknown" (tsif_selene.c)."""
    return b.get("ts") or {"in0": None, "in1": None, "evidence": "unknown"}


def _tri(v):
    return CARD_UNKNOWN if v is None else int(v)


def _check(d):
    """Check the shape of the tables, so a wrong row is never generated."""
    root = d.get("_root", HERE)
    seen_usb, none = {}, []
    for b in d["boards"]:
        where = b["_file"]
        for key in ("id", "name", "evidence", "i2c", "demod",
                    "tuner", "tuners"):
            if key not in b:
                raise SystemExit(f"{where}: '{key}' is missing")
        u = _usb(b.get("usb"))
        if u:
            if u in seen_usb:
                raise SystemExit(
                    f"{where}: USB {b['usb']} duplicates '{seen_usb[u]}'")
            seen_usb[u] = b["id"]
        else:
            none.append(where)
        sub = b["demod"]
        if sub.get("evidence") not in EV:
            raise SystemExit(f"{where}.demod: evidence is not one of {list(EV)}")
        if sub.get("driver") is None and sub["evidence"] != "unknown":
            raise SystemExit(
                f"{where}.demod: no driver but evidence is "
                f"'{sub['evidence']}'; use unknown when it is not known")
        _driver(d, "demod", sub.get("driver"), f"{where}.demod")
        # The tuner is facts only: the firmware never drives it (the host
        # tunes by I2CXFER), so there is no driver to name.
        sub = b["tuner"]
        if sub.get("evidence") not in EV:
            raise SystemExit(f"{where}.tuner: evidence is not one of {list(EV)}")
        if "driver" in sub:
            raise SystemExit(
                f"{where}.tuner: no 'driver' -- the firmware does not drive"
                " the tuner; name the part in 'part'")
        _driver(d, "i2c", b["i2c"], f"{where}.i2c")
        card = _card(b)
        if card.get("evidence") not in EV:
            raise SystemExit(f"{where}.card: evidence is not one of {list(EV)}")
        if card.get("slot") not in (True, False, None):
            raise SystemExit(f"{where}.card: slot must be true / false / null")
        if card.get("polarity") not in (0, 1, None):
            raise SystemExit(f"{where}.card: polarity must be 0 / 1 / null")
        if card["evidence"] != "unknown" and card.get("polarity") is None:
            raise SystemExit(
                f"{where}.card: polarity is null but evidence is "
                f"'{card['evidence']}'; use unknown when it is not known")
        ts = _ts(b)
        if ts.get("evidence") not in EV:
            raise SystemExit(f"{where}.ts: evidence is not one of {list(EV)}")
        if ts["evidence"] == "inferred":
            raise SystemExit(f"{where}.ts: measured or unknown only")
        if ts["evidence"] == "measured" and (ts.get("in0") is None or
                                             ts.get("in1") is None):
            raise SystemExit(f"{where}.ts: measured needs in0 and in1")
        bands = b.get("bands") or []
        if len(bands) > BAND_MAX:
            raise SystemExit(f"{where}.bands: at most {BAND_MAX}")
        for k, bd in enumerate(bands):
            w = f"{where}.bands[{k}]"
            for key in ("source", "tuned_by", "lock_seen", "record",
                        "lo_khz", "hi_khz", "step_hz"):
                if key not in bd:
                    raise SystemExit(f"{w}: '{key}' is missing")
            if bd["source"] not in SRC:
                raise SystemExit(f"{w}: source is not one of {list(SRC)}")
            if bd["tuned_by"] != "host":
                raise SystemExit(f"{w}: tuned_by is host (the firmware has"
                                 " no tune command)")
            if not 0 < int(bd["lo_khz"]) <= int(bd["hi_khz"]):
                raise SystemExit(f"{w}: need 0 < lo_khz <= hi_khz")
            if not 0 < int(bd["record"]) < 0x10000:
                raise SystemExit(f"{w}: record is 1..65535 bytes")
    if len(none) != 1:
        raise SystemExit(
            f"{len(none)} rows with usb null; there must be exactly one (the"
            " row for an image built for no device)"
            + (f": {', '.join(none)}" if none else ""))
    for kind, drivers in d["drivers"].items():
        for name, drv in drivers.items():
            for rel in [drv["source"]] + list(drv.get("requires", [])):
                if not os.path.exists(os.path.join(root, rel)):
                    raise SystemExit(
                        f"{DRIVERS}: drivers.{kind}.{name}: {rel} is missing")
    return d


def driver_sources(d):
    """Every driver source, each after what it requires."""
    srcs = []
    for kind in ("i2c", "demod"):
        for drv in d["drivers"].get(kind, {}).values():
            for rel in list(drv.get("requires", [])) + [drv["source"]]:
                if rel not in srcs:
                    srcs.append(rel)
    return srcs


def row_source(d, bid):
    """The C that defines fw_board for one device."""
    b = board(d, bid)
    parts = [("i2c", b["i2c"]), ("demod", b["demod"]["driver"])]
    ops = {kind: _driver(d, kind, name, b["id"]) for kind, name in parts}
    card = _card(b)
    c = [BANNER, "/*",
         f" * {b['name']} ({b['_file']}).",
         " * An ops field of 0 means that part of this device is not known;",
         " * the dispatch in i2c.c / demod.c returns FW_ENOTIMPL.",
         " */",
         '#include "drivers.h"', ""]
    for kind, _name in parts:
        if ops[kind]:
            c.append(f"extern const struct {kind}_ops {ops[kind]['ops']};")
    c += ["", "const struct board fw_board = {",
          f"    0x{_usb(b.get('usb')):08x}u,"]
    c.append("    " + ", ".join("&" + ops[k]["ops"] if ops[k] else "0"
                                for k, _n in parts) + ",")
    c.append(f"    {{ 0x{_num(b['demod'].get('addr_t')):02x}u,"
             f" 0x{_num(b['demod'].get('addr_t2')):02x}u,"
             f" 0x{_num(b['demod'].get('addr_s')):02x}u,"
             f" 0x{_num(b['demod'].get('addr_s2')):02x}u }},"
             f" 0x{_num(b['tuner'].get('addr')):02x}u, {int(b['tuners'])}u,")
    c.append(f"    {EV[b['demod']['evidence']]}, {EV[b['tuner']['evidence']]},")
    c.append(f"    0x{_tri(card.get('slot')):02x}u,"
             f" 0x{_tri(card.get('polarity')):02x}u, {EV[card['evidence']]},")
    bands = b.get("bands") or []
    c.append(f"    {len(bands)}u, {{")
    for bd in bands:
        flags = (["BAND_HOST_TUNED"] if bd["tuned_by"] == "host" else []) + \
                (["BAND_LOCK_SEEN"] if bd["lock_seen"] else [])
        c.append(f"        {{ {SRC[bd['source']]}, {' | '.join(flags) or '0'},"
                 f" {int(bd['record'])}u, {int(bd['lo_khz'])}u,"
                 f" {int(bd['hi_khz'])}u, {int(bd['step_hz'])}u }},")
    ts = _ts(b)
    c += ["    },",
          f"    0x{_num(ts.get('in0')):08x}u, 0x{_num(ts.get('in1')):08x}u,"
          f" {EV[ts['evidence']]},",
          "};", ""]
    return "\n".join(c)


def write_row(root, d, bid):
    """Write build/board_<bid>.c (only when it changed) -> its path."""
    text = row_source(d, bid)
    path = os.path.join(root, BUILD, f"board_{bid}.c")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    old = None
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            old = f.read()
    if old != text:
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    return path


def ran_line(boards):
    """One line saying which products have had their image run on hardware.

    The row with usb null is not counted: it names no product.
    """
    prod = [b for b in boards if b.get("usb")]
    ran = [b["id"] for b in prod if not b["_untested"]]
    return (f"products whose image has run on hardware: {len(ran)}/{len(prod)}"
            + (f" ({', '.join(ran)})" if ran else
               " -- none yet"))


def table(boards, drivers, out=print):
    """A side-by-side table of the devices.

    One file per device makes it hard to see that DT295 and M2TV reach I2C
    differently, or which device uses which demodulator, so the comparison
    lives here.  build.py --list and genboards.py print the same table.

    Names are the config keys, since those are what you edit.  `(?)` marks a
    driver whose own evidence is unknown (not checked on hardware).
    """
    def nm(kind, name):
        if not name:
            return "-"
        drv = drivers[kind][name]
        return name + ("" if drv.get("evidence") != "unknown" else " (?)")
    out(f"{'device':<10} {'I2C':<16} {'demod':<12} {'tuner':<14} evidence")
    for b in boards:
        out(f"{b['id']:<10} {nm('i2c', b['i2c']):<16} "
            f"{nm('demod', b['demod']['driver']):<12} "
            f"{(b['tuner'].get('part') or '-')[:14]:<14} "
            f"demod={b['demod']['evidence']} tuner={b['tuner']['evidence']}")


def main(argv):
    argv = list(argv)
    if argv and argv[0] in ("-h", "--help"):
        print(__doc__)
        return 0
    d = load()
    if argv[:1] == ["--c"]:
        if len(argv) != 2:
            raise SystemExit("--c needs one device id")
        sys.stdout.write(row_source(d, argv[1]))
        return 0
    if argv:
        raise SystemExit(f"unknown argument: {argv[0]}")
    print(f"{len(d['boards'])} devices ({DEVICES}/ and {UNTESTED}/), "
          f"{len(driver_sources(d))} driver sources")
    table(d["boards"], d["drivers"])
    print("\n" + ran_line(d["boards"]))
    un = untested(d)
    if un:
        print(f"{len(un)} in {UNTESTED}/ (never run on hardware): "
              + ", ".join(un))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
